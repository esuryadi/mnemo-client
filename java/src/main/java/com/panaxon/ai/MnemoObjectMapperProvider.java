package com.panaxon.ai;

import com.fasterxml.jackson.databind.DeserializationFeature;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.datatype.jsr310.JavaTimeModule;
import jakarta.ws.rs.ext.ContextResolver;

/**
 * Supplies the Jackson {@link ObjectMapper} used by the RESTEasy client: java.time support, and tolerance of
 * response fields this client version does not know about, so a newer service never breaks an older client.
 *
 * @author edward.suryadi
 * @since 1.0
 */
class MnemoObjectMapperProvider implements ContextResolver<ObjectMapper> {
    private static final ObjectMapper MAPPER = new ObjectMapper()
            .registerModule(new JavaTimeModule())
            .configure(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES, false);

    /** @return the shared mapper, for code that parses JSON outside the JAX-RS pipeline */
    static ObjectMapper mapper() {
        return MAPPER;
    }

    @Override
    public ObjectMapper getContext(Class<?> type) {
        return MAPPER;
    }
}
